// Stickman-Backend als Neon Function (ersetzt das Spring-Boot-Backend auf Render).
// Gleiche Endpunkte wie vorher: /api/stickmans, /api/stickmans/:id, /api/stickmans/owner/:owner
import { Hono } from "hono";
import { cors } from "hono/cors";
import pg from "pg";
import { attachDatabasePool } from "@neon/functions";

// Pool einmal pro Isolate, klein halten (Empfehlung Neon-Skill). DATABASE_URL wird von Neon injiziert.
// pg liefert bigint als String -> als Zahl ausgeben wie vorher bei Spring
pg.types.setTypeParser(20, (v) => Number(v));

const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 5 });
attachDatabasePool(pool);

// Tabelle wie sie Hibernate frueher angelegt hat; idempotent.
let schemaReady: Promise<unknown> | null = null;
function ensureSchema() {
  schemaReady ??= pool
    .query(
      `create table if not exists stickman (
         id bigint generated by default as identity primary key,
         name varchar(255), hat varchar(255), top varchar(255),
         bot varchar(255), owner varchar(255))`,
    )
    .catch((e) => {
      schemaReady = null;
      throw e;
    });
  return schemaReady;
}

const COLS = "id, name, hat, top, bot, owner";
const FIELDS = ["name", "hat", "top", "bot", "owner"] as const;

const app = new Hono();

app.use(
  "*",
  cors({
    origin: ["https://frontendstickman.onrender.com", "http://localhost:5173"],
    allowMethods: ["GET", "POST", "PUT", "DELETE", "OPTIONS"],
  }),
);

app.use("/api/*", async (_c, next) => {
  await ensureSchema();
  await next();
});

app.get("/", (c) => c.text("Stickman-Backend laeuft (Neon Function)."));

app.get("/api/stickmans", async (c) => {
  const { rows } = await pool.query(`select ${COLS} from stickman order by id`);
  return c.json(rows);
});

app.post("/api/stickmans", async (c) => {
  const body = await c.req.json().catch(() => null);
  if (!body || typeof body !== "object") return c.json({ error: "JSON erwartet" }, 400);
  const values = FIELDS.map((f) => {
    const v = (body as Record<string, unknown>)[f];
    return v == null ? null : String(v).slice(0, 255);
  });
  const { rows } = await pool.query(
    `insert into stickman (name, hat, top, bot, owner) values ($1, $2, $3, $4, $5) returning ${COLS}`,
    values,
  );
  return c.json(rows[0]);
});

app.get("/api/stickmans/owner/:owner", async (c) => {
  const { rows } = await pool.query(`select ${COLS} from stickman where owner = $1 order by id`, [
    c.req.param("owner"),
  ]);
  return c.json(rows);
});

app.get("/api/stickmans/:id", async (c) => {
  const id = Number(c.req.param("id"));
  if (!Number.isInteger(id)) return c.json(null);
  const { rows } = await pool.query(`select ${COLS} from stickman where id = $1`, [id]);
  return c.json(rows[0] ?? null);
});

export default app;
